    public int rolarD20() {
        return (int) (1 + Math.random() * 20);
    }

    public String sortearHabilidade() {
        String[] habilidades = {
            "Respiração Aquática",
            "Comunicação Marinha",
            "Bioluminescência",
            "Resistência à Pressão",
            "Natação Veloz"
        };

        int indice = (int) (Math.random() * habilidades.length);
        return habilidades[indice];
    }

    // Método 3: A fórmula matemática do poder
    public int calcularPoderGeral(int forca, int inteligencia, int carisma) {
        return (forca + inteligencia + carisma) / 3;
    }

