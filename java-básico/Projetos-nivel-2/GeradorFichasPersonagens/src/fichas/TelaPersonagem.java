    private void btFichaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btFichaActionPerformed
        // TODO add your handling code here:
        String nome = txtNome.getText();
    // Pega o item que foi selecionado na caixinha de opções
    String classe = comboArq.getSelectedItem().toString();

    // Pega os números que foram sorteados na tela e transforma de volta em Inteiro
    int f = Integer.parseInt(lblForca.getText());
    int i = Integer.parseInt(lblInteligencia.getText());
    int c = Integer.parseInt(lblCarisma.getText());

    // Usa as nossas engrenagens para calcular o resto
    int nivelPoder = calcularPoderGeral(f, i, c);
    String habilidadeSorteada = sortearHabilidade();

    // Monta o texto usando \n para pular as linhas na JTextArea
    String ficha = "========== FICHA DE PERSONAGEM ==========\n\n"
            + "Nome: " + nome + "\n"
            + "Arquétipo: " + classe + "\n\n"
            + "--- ATRIBUTOS ---\n"
            + "Força: " + f + "\n"
            + "Inteligência: " + i + "\n"
            + "Carisma: " + c + "\n\n"
            + "--- STATUS FINAL ---\n"
            + "Poder Geral: " + nivelPoder + "\n"
            + "Habilidade Única: " + habilidadeSorteada + "\n"
            + "=========================================";

    // Imprime na sua caixa branca!
    txtResumo.setText(ficha);
    }//GEN-LAST:event_btFichaActionPerformed

